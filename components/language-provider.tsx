const languageCodes = languages.slice(1).map((item) => item.code);
const dictionaries = Object.fromEntries(
  languageCodes.map((code, index) => [
    code,
    new Map(rows.map((row) => [row[0], row[index + 1]])),
  ]),
) as Record<Exclude<LanguageCode, "en">, Map<string, string>>;
const originals = new WeakMap<Text, string>();
const applied = new WeakMap<Text, string>();
function translateText(value: string, language: LanguageCode) {
  if (language === "en") return value;
  const dictionary = dictionaries[language];
  const lead = value.match(/^\s*/)?.[0] || "";
  const tail = value.match(/\s*$/)?.[0] || "";
  const text = value.trim();
  if (!text) return value;
  const exact = dictionary.get(text);
  return `${lead}${exact || text}${tail}`;
}

const LanguageContext = createContext<{
  language: LanguageCode;
  setLanguage: (value: LanguageCode) => void;
}>({ language: "en", setLanguage: () => {} });
export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setCurrent] = useState<LanguageCode>("en");
  useEffect(() => {
    const timer = window.setTimeout(() => {
      const stored = localStorage.getItem("smart-rto-language") || "en";
      const legacy: Record<string, LanguageCode> = {
        English: "en",
        हिन्दी: "hi",
        मराठी: "mr",
      };
      setCurrent(
        (legacy[stored] ||
          languages.find((item) => item.code === stored)?.code ||
          "en") as LanguageCode,
      );
    }, 0);
    return () => window.clearTimeout(timer);
  }, []);
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ur" ? "rtl" : "ltr";
    const apply = () => {
      const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
      );
      let node: Text | null;
      while ((node = walker.nextNode() as Text | null)) {
        if (node.parentElement?.closest("script,style,[data-no-translate]"))
          continue;
        const last = applied.get(node);
        if (
          !originals.has(node) ||
          (last !== undefined && node.nodeValue !== last)
        )
          originals.set(node, node.nodeValue || "");
        const result = translateText(originals.get(node) || "", language);
        node.nodeValue = result;
        applied.set(node, result);
      }
    };
    apply();
    const observer = new MutationObserver(() => {
      observer.disconnect();
      apply();
      observer.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true,
      });
    });
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
    });
    return () => observer.disconnect();
  }, [language]);
  const value = useMemo(
    () => ({
      language,
      setLanguage: (next: LanguageCode) => {
        localStorage.setItem("smart-rto-language", next);
        setCurrent(next);
      },
    }),
    [language],
  );
  return (
    <LanguageContext.Provider value={value}>
      <label className="global-language-select" data-no-translate>
        <span aria-hidden="true">文</span>
        <span className="sr-only">Choose language</span>
        <select
          aria-label="Choose language"
          value={language}
          onChange={(event) =>
            value.setLanguage(event.target.value as LanguageCode)
          }
        >
          {languages.map((item) => (
            <option key={item.code} value={item.code}>
              {item.name}
            </option>
          ))}
        </select>
      </label>
      {children}
    </LanguageContext.Provider>
  );
}
export function useLanguage() {
  return useContext(LanguageContext);
}
